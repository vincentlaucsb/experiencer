import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import subsetFont from "subset-font";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(repositoryRoot, "src");
const fontRoot = path.join(sourceRoot, "assets", "fonts");
const fullCssPath = path.join(fontRoot, "icofont.css");
const inputFontPath = path.join(fontRoot, "fonts", "icofont.ttf");
const outputCssPath = path.join(fontRoot, "icofont.subset.css");
const outputFontPath = path.join(fontRoot, "fonts", "icofont.subset.woff2");

// Keep the generic extension icon surface stable even when an icon is supplied
// outside this repository and therefore cannot be discovered by source scanning.
const extensionIconNames = [
    "bug",
    "check",
    "check-circled",
    "close-line",
    "cloud-download",
    "cloud-upload",
    "comment",
    "copy",
    "credit-card",
    "history",
    "light-bulb",
    "paper-plane",
    "robot",
    "search-document",
    "star",
    "upload",
];

const computedIconNames = [
    "rounded-down",
    "rounded-left",
    "rounded-right",
    "rounded-up",
];

// Preserve the application's established semantic names for the few IcoFont
// glyphs whose upstream class names are inconsistent or overly specific.
const iconAliases = new Map([
    ["file", "file-file"],
    ["line-block", "line-block-right"],
    ["list-dots", "listine-dots"],
    ["map-pin", "map-pins"],
    ["page-break", "page"],
]);

async function listSourceFiles(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    const files = await Promise.all(entries.map(async (entry) => {
        const entryPath = path.join(directory, entry.name);
        if (entry.isDirectory()) {
            if (entryPath === fontRoot) return [];
            return listSourceFiles(entryPath);
        }
        return /\.(?:ts|tsx)$/.test(entry.name) ? [entryPath] : [];
    }));
    return files.flat();
}

function discoverIconNames(source) {
    const names = new Set();
    const patterns = [
        /\bicofont-([a-z0-9-]+)/g,
        /\bicon\s*[:=]\s*["']([a-z0-9-]+)["']/g,
        /\bcreatePoprightIcon\(\s*["']([a-z0-9-]+)["']/g,
    ];
    for (const pattern of patterns) {
        for (const match of source.matchAll(pattern)) names.add(match[1]);
    }
    return names;
}

function readGlyph(css, iconName) {
    const escapedName = iconName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const rule = new RegExp(`\\.icofont-${escapedName}:before\\s*\\{[^}]*content:\\s*["']\\\\([0-9a-f]+)["'][^}]*\\}`, "i");
    const match = css.match(rule);
    if (!match) throw new Error(`IcoFont does not define icofont-${iconName}.`);
    return match[1].toLowerCase();
}

function readAllGlyphs(css) {
    const rule = /\.icofont-([a-z0-9-]+):before\s*\{[^}]*content:\s*["']\\([0-9a-f]+)["'][^}]*\}/gi;
    return [...css.matchAll(rule)].map((match) => ({
        iconName: match[1],
        codePoint: match[2].toLowerCase(),
    }));
}

function createSubsetCss(glyphs, fullGlyphs) {
    const aliasRules = glyphs
        .filter(({ iconName }) => iconAliases.has(iconName))
        .map(({ iconName, codePoint }) => (
            `.icofont-${iconName}:before { content: "\\${codePoint}"; }`
        ));
    const compatibilityRules = fullGlyphs.map(({ iconName, codePoint }) => (
        `.icofont-${iconName}:before { content: "\\${codePoint}"; }`
    ));
    return `/*
 * IcoFont subset generated by scripts/generate-icofont-subset.mjs.
 * Original project: https://icofont.com/
 * License: https://icofont.com/license/
 */
@font-face {
  font-family: "IcoFont";
  font-style: normal;
  font-weight: 400;
  src: url("fonts/icofont.subset.woff2") format("woff2");
}

@font-face {
  font-family: "IcoFont Full";
  font-style: normal;
  font-weight: 400;
  src: url("fonts/icofont.woff2") format("woff2");
}

[class*=" icofont-"],
[class^="icofont-"] {
  direction: ltr;
  font-family: "IcoFont", "IcoFont Full" !important;
  font-feature-settings: "liga";
  font-style: normal;
  font-variant: normal;
  font-weight: 400;
  line-height: 1;
  speak: none;
  text-transform: none;
  white-space: nowrap;
  word-wrap: normal;
  -webkit-font-smoothing: antialiased;
}

${compatibilityRules.join("\n")}
${aliasRules.join("\n")}
`;
}

async function generateSubset() {
    const sourceFiles = await listSourceFiles(sourceRoot);
    const names = new Set([...extensionIconNames, ...computedIconNames]);
    for (const sourceFile of sourceFiles) {
        const source = await readFile(sourceFile, "utf8");
        for (const name of discoverIconNames(source)) names.add(name);
    }

    const fullCss = await readFile(fullCssPath, "utf8");
    const missingNames = [];
    const glyphs = [...names]
        .sort()
        .flatMap((iconName) => {
            try {
                return [{ iconName, codePoint: readGlyph(fullCss, iconAliases.get(iconName) ?? iconName) }];
            } catch {
                missingNames.push(iconName);
                return [];
            }
        });
    if (missingNames.length > 0) {
        throw new Error(`IcoFont does not define: ${missingNames.join(", ")}.`);
    }
    const characters = glyphs
        .map(({ codePoint }) => String.fromCodePoint(Number.parseInt(codePoint, 16)))
        .join("");
    const inputFont = await readFile(inputFontPath);
    const outputFont = await subsetFont(inputFont, characters, { targetFormat: "woff2" });
    return {
        css: createSubsetCss(glyphs, readAllGlyphs(fullCss)),
        font: outputFont,
        iconCount: glyphs.length,
    };
}

async function assertCurrent(expected, outputPath) {
    let actual;
    try {
        actual = await readFile(outputPath);
    } catch {
        throw new Error(`${path.relative(repositoryRoot, outputPath)} is missing; run npm run icons:generate.`);
    }
    const isCurrent = Buffer.isBuffer(expected)
        ? actual.equals(expected)
        : normalizeNewlines(actual.toString("utf8")) === normalizeNewlines(expected);
    if (!isCurrent) {
        throw new Error(`${path.relative(repositoryRoot, outputPath)} is stale; run npm run icons:generate.`);
    }
}

function normalizeNewlines(value) {
    return value.replace(/\r\n?/g, "\n");
}

const generated = await generateSubset();
if (process.argv.includes("--check")) {
    await assertCurrent(generated.css, outputCssPath);
    await assertCurrent(generated.font, outputFontPath);
    console.log(`IcoFont subset is current (${generated.iconCount} icons, ${generated.font.length} bytes).`);
} else {
    await writeFile(outputCssPath, generated.css);
    await writeFile(outputFontPath, generated.font);
    console.log(`Generated ${generated.iconCount} IcoFont icons (${generated.font.length} bytes).`);
}
